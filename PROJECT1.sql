-- 5.How have global emissions changed year over year?

select year,
		emission_year,
        emission_year-lag(emission_year) over(order by year) as emission_change
from(SELECT YEAR,SUM(EMISSION) AS EMISSION_YEAR 
FROM EMISSION_3
where ENERGY_TYPE <> 'CO2 emissions (MMtonnes CO2)'
GROUP BY YEAR) as f;

/*This measures how total global emissions change from one year to the next using LAG().
 A positive change means emissions increased, while a negative change means they decreased.*/



-- 6.What is the trend in GDP for each country over the given years?

select country,year,value,
((value-lag(value) over(partition by country order by year))
