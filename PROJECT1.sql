-- 10.What is the emission-to-GDP ratio for each country by year? 

WITH emi_table AS (
    SELECT country, year, SUM(emission) AS sum_em
    FROM emission_3
    WHERE energy_type <> 'CO2 emissions (MMtonnes CO2)'
    GROUP BY country, year
)
SELECT e.country,
       e.year,
       e.sum_em / g.value AS ratio
FROM emi_table e
JOIN gdp_3 g
  ON e.country = g.country
 AND e.year = g.year
ORDER BY e.country, e.year;

# A higher ratio means more emissions are produced relative to the country's economic output.


-- 11.What is the energy consumption per capita for each country over the last decade? 

