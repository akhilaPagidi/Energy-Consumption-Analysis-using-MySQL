-- 16.which countries improved (reduced) their per capita emissions the most over the last decade? 

 WITH emi AS (
    SELECT country, year, SUM(emission) AS total_emission
    FROM emission_3
    WHERE energy_type <> 'CO2 emissions (MMtonnes CO2)' and year >= YEAR(CURDATE()) - 10
    GROUP BY country, year
),
pc AS (
    SELECT e.country,
           e.year,
           e.total_emission / p.value AS emission_per_capita
    FROM emi e
    JOIN population p
      ON e.country = p.countries
     AND e.year = p.year
),
change_1 AS (
    SELECT country,
           year,
           emission_per_capita,
           emission_per_capita -
           LAG(emission_per_capita)
           OVER (PARTITION BY country ORDER BY year) AS yearly_change
    FROM pc
)
SELECT country,
       AVG(yearly_change) AS avg_yearly_change
FROM change_1
GROUP BY country
ORDER BY avg_yearly_change;

#negatuve value is reduction in emission

-- What is the global share (%) of emissions by country? 

SELECT country,
       sum_emissions / (SELECT SUM(emission)
                        FROM emission_3
                        WHERE energy_type <> 'CO2 emissions (MMtonnes CO2)') * 100
       AS global_share
FROM (
    SELECT country, SUM(emission) AS sum_emissions
    FROM emission_3
    WHERE energy_type <> 'CO2 emissions (MMtonnes CO2)'
    GROUP BY country
) AS em
ORDER BY global_share DESC;

/*china has highest share of emissions,followed by United States and India
It shows how much each country contributes to the overall emissions represented in the dataset.*/

-- What is the global average GDP, emission, and population by year?
 
 WITH population_avg as (
    SELECT year, AVG(value) AS avg_p
    FROM population
    GROUP BY year),
gdp_avg as (
    SELECT year, AVG(value) AS avg_g
    FROM gdp_3
    GROUP BY year),

emission_country AS (
    SELECT country, year, SUM(emission) AS total_emission
    FROM emission_3
    WHERE energy_type <> 'CO2 emissions (MMtonnes CO2)'
    GROUP BY country, year
),
emission_avg AS (
    SELECT year, AVG(total_emission) AS avg_e
    FROM emission_country
    GROUP BY year
)

SELECT
    p.year,p.avg_p,g.avg_g,e.avg_e
FROM population_avg p
LEFT JOIN 
gdp_avg g
on p.year = g.year
LEFT JOIN emission_avg e
on p.year = e.year
ORDER BY p.year;

/*It shows how the average values have 
changed over time rather than representing the world's total GDP, emissions, or population.*/




