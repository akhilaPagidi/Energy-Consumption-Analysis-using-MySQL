-- 13.Which countries have the highest energy consumption relative to GDP?

WITH consum AS (
    SELECT country, SUM(consumption) AS total_consumption
    FROM consumption
    WHERE year = (SELECT MAX(year) FROM consumption)
    GROUP BY country
)
SELECT c.country,
       c.total_consumption,
       g.value AS GDP,   
       c.total_consumption / g.value AS ratio
FROM consum c
JOIN gdp_3 g
  ON c.country = g.country
 AND g.year = (SELECT MAX(year) FROM gdp_3)
ORDER BY ratio DESC
LIMIT 10;
/*This compares a country's energy consumption with its GDP. 
It helps identify countries that use relatively more energy for their level of economic output.*/


-- 14.What is the correlation between GDP growth and energy production growth? 


WITH prod_table AS (
    SELECT country, year, SUM(production) AS sum_prod
    FROM production
    GROUP BY year, country
),
growth_table AS (
    SELECT
        p.country,
        p.year,
        p.sum_prod,
        g.value,
        p.sum_prod - LAG(p.sum_prod)
            OVER (PARTITION BY p.country ORDER BY p.year) AS prod_growth,
        g.value - LAG(g.value)
            OVER (PARTITION BY p.country ORDER BY p.year) AS gdp_growth
    FROM prod_table p
    LEFT JOIN gdp_3 g
      ON p.year = g.year
     AND p.country = g.country
)
SELECT *
FROM growth_table
ORDER BY country, year;
#This compares year-over-year GDP growth with energy production growth for each country. 



