-- 8.Has energy consumption increased or decreased over the years for major economies?

WITH major_economies AS (
    SELECT country
    FROM gdp_3
    WHERE year = (SELECT MAX(year) FROM gdp_3)
    ORDER BY value DESC
    LIMIT 5
)

SELECT
    c.country,c.year,SUM(c.consumption) AS total_consumption,
    SUM(c.consumption) -LAG(SUM(c.consumption)) OVER (PARTITION BY c.country ORDER BY c.year) AS yearly_change
FROM consumption c
JOIN major_economies m
    ON c.country = m.country
GROUP BY c.country, c.year
ORDER BY c.country, c.year;
/* china and india's consumption of energy has increased,but not other major economies*/

-- 9.What is the average yearly change in emissions per capita for each country?

with emi_table as(
select country,year,sum(emission) as sum_em
from emission_3 e
WHERE energy_type <> 'CO2 emissions (MMtonnes CO2)'
group by year,country
order by country,year),

per_capita as (select e.country,e.year,e.sum_em/p.value as emission_per_capita
				from emi_table e
                join
                population p
                on e.country=p.countries and e.year=p.year),
                
yearly_change as(select o.year,o.country,o.emission_per_capita-lag(emission_per_capita) 
				over(partition by country order by year) as yearly_change
				from per_capita o)

select country,avg(yearly_change) as avg_yearly_change
from yearly_change
group by country;

/*A negative average change indicates that per-capita emissions have generally decreased.*/

